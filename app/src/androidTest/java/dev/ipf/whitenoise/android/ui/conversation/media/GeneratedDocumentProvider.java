package dev.ipf.whitenoise.android.ui.conversation.media;

import android.content.ContentProvider;
import android.content.ContentValues;
import android.content.pm.PackageManager;
import android.database.Cursor;
import android.database.MatrixCursor;
import android.net.Uri;
import android.os.Binder;
import android.os.ParcelFileDescriptor;
import android.os.Process;
import android.provider.OpenableColumns;
import java.io.FileNotFoundException;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.List;

/**
 * Serves generated documents as {@code content://} sources, so a device fixture picks a file through the same
 * content resolver path a real document pick takes. Bytes stream through a pipe, so a 512 MiB document needs no
 * file of its own on the device.
 *
 * <p>It is written in Java because it runs in the test APK's own process, which carries no Kotlin runtime. It is
 * exported because the instrumented app reads it under its own uid, but it answers only callers signed like this
 * test APK. It lives only in the test APK and serves only generated bytes, read-only.
 */
public final class GeneratedDocumentProvider extends ContentProvider {
    private static final String AUTHORITY_SUFFIX = ".generated-documents";
    private static final String OCTET_STREAM_MIME_TYPE = "application/octet-stream";
    private static final int COPY_BUFFER_BYTES = 64 * 1024;

    /** The URI of a generated document of {@code length} bytes named {@code name}, served by {@code testPackage}. */
    public static Uri uri(String testPackage, long length, String name) {
        return new Uri.Builder()
                .scheme("content")
                .authority(testPackage + AUTHORITY_SUFFIX)
                .appendPath(Long.toString(length))
                .appendPath(name)
                .build();
    }

    /** The SHA-256 of the first {@code length} generated bytes, computed apart from any reader of the provider. */
    public static String sha256(long length) throws IOException {
        MessageDigest digest;
        try {
            digest = MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException error) {
            throw new IllegalStateException(error);
        }
        byte[] buffer = new byte[COPY_BUFFER_BYTES];
        try (InputStream input = new GeneratedBytes(length)) {
            for (int n = input.read(buffer); n >= 0; n = input.read(buffer)) {
                digest.update(buffer, 0, n);
            }
        }
        StringBuilder hex = new StringBuilder();
        for (byte value : digest.digest()) {
            hex.append(String.format("%02x", value));
        }
        return hex.toString();
    }

    /** Nothing to set up: every document is computed from its URI. */
    @Override
    public boolean onCreate() {
        return true;
    }

    /** Every generated document is opaque bytes. */
    @Override
    public String getType(Uri uri) {
        return OCTET_STREAM_MIME_TYPE;
    }

    /** Answers the name and declared size a picker reads before it opens the stream. */
    @Override
    public Cursor query(
            Uri uri,
            String[] projection,
            String selection,
            String[] selectionArgs,
            String sortOrder) {
        requireSameSigner();
        long length = lengthOf(uri);
        String name = nameOf(uri);
        String[] columns =
                projection != null
                        ? projection
                        : new String[] {OpenableColumns.DISPLAY_NAME, OpenableColumns.SIZE};
        Object[] values = new Object[columns.length];
        for (int index = 0; index < columns.length; index++) {
            if (OpenableColumns.DISPLAY_NAME.equals(columns[index])) {
                values[index] = name;
            } else if (OpenableColumns.SIZE.equals(columns[index])) {
                values[index] = length;
            }
        }
        MatrixCursor cursor = new MatrixCursor(columns, 1);
        cursor.addRow(values);
        return cursor;
    }

    /**
     * Streams the document through a pipe from a background thread. A reader that stops early, as a sniffed
     * header or a refused pick does, only ends that writer, and a writer that stops early closes its end with an
     * error rather than as a complete document.
     */
    @Override
    public ParcelFileDescriptor openFile(Uri uri, String mode) throws FileNotFoundException {
        requireSameSigner();
        if (!"r".equals(mode)) {
            throw new IllegalArgumentException("Generated documents are read-only");
        }
        long length = lengthOf(uri);
        ParcelFileDescriptor[] pipe;
        try {
            pipe = ParcelFileDescriptor.createReliablePipe();
        } catch (IOException error) {
            throw new FileNotFoundException("Generated document pipe unavailable");
        }
        ParcelFileDescriptor write = pipe[1];
        Thread writer =
                new Thread(
                        () -> {
                            boolean complete = false;
                            try (InputStream input = new GeneratedBytes(length)) {
                                // The descriptor stays owned by the pipe, which closeWriter closes once.
                                OutputStream output = new FileOutputStream(write.getFileDescriptor());
                                byte[] buffer = new byte[COPY_BUFFER_BYTES];
                                for (int n = input.read(buffer); n >= 0; n = input.read(buffer)) {
                                    output.write(buffer, 0, n);
                                }
                                complete = true;
                            } catch (IOException error) {
                                // The reader closed its end before the last byte.
                            }
                            closeWriter(write, complete);
                        },
                        "generated-document");
        writer.setDaemon(true);
        writer.start();
        return pipe[0];
    }

    /** Generated documents are read-only. */
    @Override
    public Uri insert(Uri uri, ContentValues values) {
        throw new UnsupportedOperationException("Generated documents are read-only");
    }

    /** Generated documents are read-only. */
    @Override
    public int delete(Uri uri, String selection, String[] selectionArgs) {
        throw new UnsupportedOperationException("Generated documents are read-only");
    }

    /** Generated documents are read-only. */
    @Override
    public int update(Uri uri, ContentValues values, String selection, String[] selectionArgs) {
        throw new UnsupportedOperationException("Generated documents are read-only");
    }

    /** Refuses any caller not signed like this test APK, so only the instrumented app reads generated bytes. */
    private void requireSameSigner() {
        PackageManager packages = getContext().getPackageManager();
        if (packages.checkSignatures(Binder.getCallingUid(), Process.myUid()) != PackageManager.SIGNATURE_MATCH) {
            throw new SecurityException("Generated documents are served only to the instrumented app");
        }
    }

    /** Closes the pipe's write end, as a complete document or with an error the reader can detect. */
    private static void closeWriter(ParcelFileDescriptor write, boolean complete) {
        try {
            if (complete) {
                write.close();
            } else {
                write.closeWithError("Generated document stopped before its last byte");
            }
        } catch (IOException error) {
            // The reader is gone, so nothing is left to tell.
        }
    }

    /** The document's length, the first path segment, refusing anything that is not a non-negative number. */
    private static long lengthOf(Uri uri) {
        List<String> segments = uri.getPathSegments();
        if (segments.size() != 2) {
            throw new IllegalArgumentException("Generated document URI needs a length and a name");
        }
        long length = Long.parseLong(segments.get(0));
        if (length < 0) {
            throw new IllegalArgumentException("Generated document length is negative");
        }
        return length;
    }

    /** The document's display name, the second path segment. */
    private static String nameOf(Uri uri) {
        List<String> segments = uri.getPathSegments();
        if (segments.size() != 2) {
            throw new IllegalArgumentException("Generated document URI needs a length and a name");
        }
        return segments.get(1);
    }

    /** Deterministic pseudo-random bytes of a fixed length, the same sequence for every reader. */
    static final class GeneratedBytes extends InputStream {
        private final long length;
        private long produced;
        private long state = -0x61c8864680b583ebL;

        /** A sequence of {@code length} bytes, starting from the fixed seed. */
        GeneratedBytes(long length) {
            this.length = length;
        }

        /** Produces one byte. */
        @Override
        public int read() {
            byte[] one = new byte[1];
            return read(one, 0, 1) < 0 ? -1 : one[0] & 0xFF;
        }

        /** Fills {@code buffer} with the next bytes of the sequence. */
        @Override
        public int read(byte[] buffer, int offset, int count) {
            if (produced >= length) {
                return -1;
            }
            int n = (int) Math.min(count, length - produced);
            for (int index = 0; index < n; index++) {
                state ^= state << 13;
                state ^= state >>> 7;
                state ^= state << 17;
                buffer[offset + index] = (byte) state;
            }
            produced += n;
            return n;
        }
    }
}
