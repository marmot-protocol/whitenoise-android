#!/usr/bin/env python3
"""Emit the exact classic-BPF process-creation restriction compiled into the worker."""
import argparse
from pathlib import Path

# Linux UAPI values are checked against the selected NDK headers by the C++ wrapper.
ABIS = {
    "arm64-v8a": ("__aarch64__", 0xC00000B7, 220, -1, -1, 221, 281, 277),
    "armeabi-v7a": ("__arm__", 0x40000028, 120, 2, 190, 11, 387, 383),
    "x86": ("__i386__", 0x40000003, 120, 2, 190, 11, 358, 354),
    "x86_64": ("__x86_64__", 0xC000003E, 56, 57, 58, 59, 322, 317),
}
CLONE3 = 435
THREAD_FLAGS = 0x10900  # CLONE_THREAD | CLONE_VM | CLONE_SIGHAND
X32_BIT = 0x40000000
KILL_PROCESS = 0x80000000
ALLOW = 0x7FFF0000
DENY = 0x00050001  # SECCOMP_RET_ERRNO | EPERM


def program(abi):
    _, audit, clone, fork, vfork, execve, execveat, _ = ABIS[abi]
    instructions = []
    labels = {}

    def label(name):
        labels[name] = len(instructions)

    def emit(code, value, yes=0, no=0):
        instructions.append((code, yes, no, value))

    emit(0x20, 4)  # LD W ABS seccomp_data.arch
    emit(0x15, audit, "nr", "kill")
    label("kill")
    emit(0x06, KILL_PROCESS)
    label("nr")
    emit(0x20, 0)  # LD W ABS seccomp_data.nr
    if abi == "x86_64":
        emit(0x45, X32_BIT, "deny")  # JSET: reject the x32 syscall ABI.
    for number in (fork, vfork, CLONE3, execve, execveat):
        if number >= 0:
            emit(0x15, number, "deny")
    emit(0x15, clone, "clone", "allow")
    label("clone")
    emit(0x20, 16)  # LD W ABS low32(seccomp_data.args[0]); all targets are LE.
    emit(0x54, THREAD_FLAGS)  # AND K: all three thread-sharing flags are mandatory.
    emit(0x15, THREAD_FLAGS, "allow", "deny")
    label("allow")
    emit(0x06, ALLOW)
    label("deny")
    emit(0x06, DENY)
    result = []
    for index, (code, yes, no, value) in enumerate(instructions):
        resolve = lambda jump: labels[jump] - index - 1 if isinstance(jump, str) else jump
        yes, no = resolve(yes), resolve(no)
        if not (0 <= yes <= 255 and 0 <= no <= 255):
            raise ValueError("classic-BPF branch outside bounded forward program")
        result.append((code, yes, no, value))
    return result


def header():
    lines = ["// Generated by generate_seccomp_filter.py; do not edit.", "#pragma once", ""]
    for index, (abi, (macro, audit, clone, fork, vfork, execve, execveat, seccomp)) in enumerate(ABIS.items()):
        lines += [f"#{'if' if index == 0 else 'elif'} defined({macro})", f"// ABI {abi}"]
        for name, value in (("AuditArch", audit), ("Clone", clone), ("Fork", fork), ("Vfork", vfork),
                            ("Execve", execve), ("Execveat", execveat), ("Seccomp", seccomp), ("Clone3", CLONE3)):
            lines.append(f"constexpr {'uint32_t' if name == 'AuditArch' else 'int'} kSandbox{name} = {value};")
        lines.append("static const sock_filter kMediaProcessFilter[] = {")
        lines += [f"    {{0x{code:02x}, {yes}, {no}, 0x{value:08x}U}}," for code, yes, no, value in program(abi)]
        lines += ["};", ""]
    lines += ["#else", '#error "Unsupported media worker syscall ABI"', "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).with_name("seccomp_filter.h")
    expected = header()
    if args.check:
        if path.read_text() != expected:
            parser.error("committed seccomp program differs from its generator")
    else:
        path.write_text(expected)


if __name__ == "__main__":
    main()
